// Service layer for the `stock_dresses` table (F17 — Stock Dress Inventory).
// See docs/inventauri_requirements.md §7a for the full feature spec.
//
// Convention: components never call `supabase.from(...)` directly.
// Every table gets one service file exporting plain async functions.
// Each function returns { data, error } — same shape Supabase itself uses.

import { supabase } from "$lib/supabaseClient";

/**
 * Fetch all stock dresses, newest first.
 * @returns {Promise<{ data: any[] | null, error: string | null }>}
 */
export async function listStockDresses() {
	const { data, error } = await supabase
		.from("stock_dresses")
		.select("*")
		.order("created_at", { ascending: false });

	if (error) {
		console.error("listStockDresses failed:", error.message);
		return { data: null, error: error.message };
	}
	return { data, error: null };
}

/**
 * Fetch a single stock dress by id, including its images and variants
 * (with each variant's axis values) — enough for the detail drawer.
 * @param {string} id
 * @returns {Promise<{ data: any | null, error: string | null }>}
 */
export async function getStockDressById(id) {
	const { data, error } = await supabase
		.from("stock_dresses")
		.select(
			`*,
			stock_dress_images (*),
			stock_dress_variants (*, stock_dress_variant_values (*))`,
		)
		.eq("id", id)
		.single();

	if (error) {
		console.error("getStockDressById failed:", error.message);
		return { data: null, error: error.message };
	}
	return { data, error: null };
}

/**
 * Create a new stock dress. `sku` is generated by the database — never pass it.
 * @param {{ name: string, garment_type: string, category: string, subcategory?: string, base_price: number, production_cost?: number, notes?: string }} dress
 * @returns {Promise<{ data: any | null, error: string | null }>}
 */
export async function createStockDress(dress) {
	const { data, error } = await supabase
		.from("stock_dresses")
		.insert(dress)
		.select()
		.single();

	if (error) {
		console.error("createStockDress failed:", error.message);
		return { data: null, error: error.message };
	}
	return { data, error: null };
}

/**
 * Update fields on an existing stock dress. Never pass `sku` — it is
 * database-generated and immutable after creation.
 * @param {string} id
 * @param {{ name?: string, garment_type?: string, category?: string, subcategory?: string | null, base_price?: number, production_cost?: number | null, notes?: string | null, status?: string }} updates
 * @returns {Promise<{ data: any | null, error: string | null }>}
 */
export async function updateStockDress(id, updates) {
	const { data, error } = await supabase
		.from("stock_dresses")
		.update(updates)
		.eq("id", id)
		.select()
		.single();

	if (error) {
		console.error("updateStockDress failed:", error.message);
		return { data: null, error: error.message };
	}
	return { data, error: null };
}

/**
 * Soft-delete: sets status to 'archived'. Never hard-deletes a dress —
 * matches the Available/Reserved/Sold/Archived lifecycle in the schema.
 * @param {string} id
 * @returns {Promise<{ data: any | null, error: string | null }>}
 */
export async function archiveStockDress(id) {
	return updateStockDress(id, { status: "archived" });
}
